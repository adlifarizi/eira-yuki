/**
 * Role of the user interacting with the companion.
 * - 'owner': Primary master/owner with administrative and full tool privileges.
 * - 'guest': External user or group participant with restricted public-only tools.
 */
export type UserRole = 'owner' | 'guest';

/**
 * Map of adapter platform identifiers to lists of authorized owner user/phone IDs.
 * E.g., { whatsapp: ['628123456789'], discord: ['123456789012345678'] }
 */
export type BotOwners = Record<string, string[]>;

/**
 * Type of chat session where the message was received.
 * - 'dm': Direct one-on-one message.
 * - 'group': Group chat with multiple participants.
 */
export type ChatType = 'dm' | 'group';

/**
 * Normalized multimedia attachment attached to an incoming message.
 */
export interface IncomingMedia {
  /** Raw binary buffer of the downloaded media. */
  buffer: Buffer;
  /** MIME type (e.g. "image/jpeg", "image/png", "audio/ogg"). */
  mimeType: string;
  /** High-level category of the media content. */
  type: 'image' | 'video' | 'audio';
}

/**
 * Quoted or replied message context attached to an incoming message.
 */
export interface QuotedMessage {
  /** Identifier or phone number of the original quoted sender. */
  senderId: string;
  /** Text content of the quoted message. */
  text: string;
}

/**
 * Normalized incoming message ingested by the core agent pipeline.
 * Standardizes messages originating from chat platforms (e.g. WhatsApp via Baileys).
 */
export interface IncomingMessage {
  /** Unique message identifier assigned by the messaging platform. */
  id: string;
  /** Phone number or unique ID of the sender. */
  senderId: string;
  /** Display name or push name of the sender. */
  senderName: string;
  /** Target chat identifier (Group chat ID or DM chat ID). */
  chatId: string;
  /** Indicates whether this message came from a direct message or a group chat. */
  chatType: ChatType;
  /** Authorization role of the sender determined by permission checks. */
  role: UserRole;
  /** Text content of the message. */
  text: string;
  /** Optional media attachment if the user sent an image, audio, or video. */
  media?: IncomingMedia;
  /** Optional secondary media (e.g. quoted audio paired with an image/video command). */
  secondaryMedia?: IncomingMedia;
  /** Context of any quoted or replied message. */
  quotedMessage?: QuotedMessage;
  /** Unix timestamp in milliseconds when the message was received. */
  timestamp: number;
  /** Identifier of the messaging adapter platform (e.g. "whatsapp", "discord", "telegram"). */
  adapter?: string;
}

/**
 * Normalized rich media attachment dispatched with an agent response.
 */
export interface ResponseAttachment {
  /** Media classification of the attachment. */
  type: 'sticker' | 'image';
  /** Binary data buffer or string content (e.g. URI/file path). */
  payload: Buffer | string;
  /** Optional metadata associated with the attachment (e.g. sticker tag, mimeType). */
  metadata?: Record<string, unknown>;
}

/**
 * JSON Schema specification describing parameter types, properties, and constraints for a tool.
 * Conforms to standard OpenAPI/JSON Schema subsets accepted by LLM function calling protocols.
 */
export interface ToolParameterSchema {
  /** The root data type, typically "object". */
  type: string;
  /** Human-readable description explaining what this parameter object represents. */
  description?: string;
  /** Schema definitions for each property of the parameter object. */
  properties?: Record<string, any>;
  /** List of property names that are required for execution. */
  required?: string[];
  /** Item schema definition when type is "array". */
  items?: any;
}

/**
 * Universal tool metadata exposed to the LLM for function calling.
 * Contains only declarative schema information without implementation logic.
 */
export interface ToolDefinition {
  /** Unique identifier of the tool (e.g. "web_search", "send_sticker"). */
  name: string;
  /** Clear description explaining what the tool does and when the model should invoke it. */
  description: string;
  /** Parameter schema defining the arguments the model must supply. */
  parameters: ToolParameterSchema;
}

/**
 * Standardized payload representing a function/tool invocation emitted by an LLM.
 */
export interface ToolCall {
  /** Optional call identifier generated by the provider (e.g. OpenAI tool_call_id). */
  id?: string;
  /** Name of the tool to be executed. */
  name: string;
  /** Key-value arguments provided by the model for the tool invocation. */
  args: Record<string, any>;
  /** Opaque thought signature emitted by thinking models (e.g. Gemini 2.5/3.x) that must be echoed back on continuation. */
  thoughtSignature?: string;
}

/**
 * Outcome payload of a tool execution returned back to the LLM provider for multi-hop continuation.
 */
export interface ToolResult {
  /** Optional identifier linking back to the originating ToolCall. */
  toolCallId?: string;
  /** Name of the tool that was executed. */
  toolName: string;
  /** JSON-serializable execution result or error payload. */
  result: any;
}

/**
 * Abstraction for resolving and describing reaction stickers without coupling core to filesystem utilities.
 */
export interface StickerResolver {
  /** Retrieves a sticker binary buffer by ID or tag, or null if not found. */
  getSticker(idOrTag: string): Buffer | null;
  /** Formats available stickers into a concise description for LLM tool schemas. */
  describeForTools(): string;
}

/**
 * Final standardized response produced by EiraAgent to be dispatched back to the messaging adapter.
 */
export interface CoreResponse {
  /** Primary natural language text response to be sent to the user. */
  text: string;
  /** Optional web sources or search grounding citations referenced by the response. */
  sources?: { title: string; url: string }[];
  /** Optional rich media attachment (e.g. reaction sticker or generated image) to be dispatched by the adapter. */
  attachment?: ResponseAttachment;
  /** Diagnostic list of tools executed during this conversation turn. */
  actionsExecuted?: { toolName: string; result: any }[];
}
